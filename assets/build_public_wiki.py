def apply_redact(text: str, page: str) -> str:
    for pg, pat, rep in REDACT:
        if pg is None or pg == page:
            text = re.sub(pat, rep, text)
    return text

def scrub(text: str, page: str) -> str:
    # —— 通用：手机号 ——
    text = re.sub(r"1[3-9]\d{9}", "（联系方式已脱敏）", text)
    # —— 对接人姓名 ——
    text = text.replace("张永强局长，（联系方式已脱敏）", "（对接联系人信息内部保留）")
    text = text.replace("（张永强局长）", "")
    text = text.replace("张永强", "对接单位负责人")
    # —— 02 团队页：删除学号列 ——
    if page == "02_团队与分工":
        text = text.replace("| 姓名 | 学号 | 年级 | 分工（v4 定岗） |",
                            "| 姓名 | 年级 | 分工 |")
        text = text.replace("|------|------|------|------|",
                            "|------|------|------|", 1)  # 仅成员表的 4 列分隔行
        text = re.sub(r"\|\s*1001\d{6}\s*\|", "|", text)   # 删除学号单元格
        # 删除内部管理制度整节（三要素考核 + 五项日常制度）
        text = re.sub(r'## 岗位"三要素"管理.*?(?=## 协作机制)', "", text,
                      flags=re.DOTALL)
        # 删除分工调整内部记录
        text = re.sub(r"- \*\*2026-08-12 分工调整\*\*[^\n]*\n", "", text)
    return text

def relink(text: str) -> str:
    def repl(m):
        target = m.group(1).strip()
        label = m.group(2).strip() if m.group(2) else target
        # 显示名去掉序号前缀
        disp = label.split("_", 1)[-1] if "_" in label else label
        if target in PUBLIC:
            return f"[{disp}]({target}.md)"
        return f"{disp}（内部资料）"
    return re.sub(r"\[\[([^\]|]+)(?:\|([^\]]+))?\]\]", repl, text)

